#include <vanetza/security/ecies.hpp>
#include <gtest/gtest.h>
#include <array>
#include <cstdint>

using vanetza::ByteBuffer;
using vanetza::create_byte_view;
using namespace vanetza::security;

namespace
{

// AES key and recipient info shared by IEEE 1609.2-2016 Annex D.6.2 ECIES1 and ECIES2 test vectors
const Aes128Key d62_aes_key {{
    0x91, 0x69, 0x15, 0x5B, 0x08, 0xB0, 0x76, 0x74,
    0xCB, 0xAD, 0xF7, 0x5F, 0xB4, 0x6A, 0x7B, 0x0D
}};
const Sha256Hash d62_recipient_info {{
    0xA6, 0xB7, 0xB5, 0x25, 0x54, 0xB4, 0x20, 0x3F,
    0x7E, 0x3A, 0xCF, 0xDB, 0x3A, 0x3E, 0xD8, 0x67,
    0x4E, 0xE0, 0x86, 0xCE, 0x59, 0x06, 0xA7, 0xCA,
    0xC2, 0xF8, 0xA3, 0x98, 0x30, 0x6D, 0x3B, 0xE9
}};

} // anonymous namespace

// IEEE 1609.2-2016 Annex D.6.2 ECIES1 test vector
TEST(Ecies, encrypt_key_IEEE_1609_2_Annex_D_6_2_ECIES1)
{
    // Shared secret z = x-coord of [k_E] * Q_recipient (precomputed)
    const ByteBuffer shared_secret {{
        0xd4, 0x43, 0x08, 0x02, 0x3f, 0xbb, 0xd3, 0xe9,
        0x06, 0xb9, 0xf3, 0xb4, 0x0e, 0x5e, 0x0b, 0x62,
        0x54, 0x11, 0x70, 0x3c, 0x4a, 0x99, 0x24, 0x9d,
        0x35, 0xa1, 0x39, 0x06, 0x38, 0x6a, 0x3e, 0xe3
    }};
    const std::array<std::uint8_t, 16> expected_wrapped {{
        0xA6, 0x34, 0x20, 0x13, 0xD6, 0x23, 0xAD, 0x6C,
        0x5F, 0x68, 0x82, 0x46, 0x96, 0x73, 0xAE, 0x33
    }};
    const KeyTag expected_tag {{
        0x80, 0xE1, 0xD8, 0x5D, 0x30, 0xF1, 0xBA, 0xE4,
        0xEC, 0xF1, 0xA5, 0x34, 0xA8, 0x9A, 0x07, 0x86
    }};

    PublicKey ephemeral_key;
    ephemeral_key.type = KeyType::NistP256;
    ephemeral_key.compression = KeyCompression::Y0;
    ephemeral_key.x = ByteBuffer(32, 0x42);

    const EncryptedSymmetricKey encrypted =
        encrypt_key(ephemeral_key, create_byte_view(shared_secret), d62_aes_key, d62_recipient_info);

    EXPECT_EQ(ephemeral_key.x, encrypted.public_key.x);
    EXPECT_EQ(expected_wrapped, encrypted.wrapped_key);
    EXPECT_EQ(expected_tag, encrypted.authentication_tag);
}

// IEEE 1609.2-2016 Annex D.6.2 ECIES2 test vector
