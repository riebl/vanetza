#include "mock_credential_storage.hpp"
#include "openssl_security_module.hpp"
#include <gtest/gtest.h>
#include <openssl/ec.h>
#include <openssl/err.h>

using vanetza::ByteBuffer;
using vanetza::expected;
using vanetza::security::Aes128Key;
using vanetza::security::SecurityModuleError;
using namespace vanetza::pki;

class OpenSslSecurityModuleTest : public ::testing::Test
{
protected:
    void SetUp() override
    {
        // some tests check that the module leaves no errors in OpenSSL's error queue
        ERR_clear_error();
    }

    std::shared_ptr<MockCredentialStorage> credentials = std::make_shared<MockCredentialStorage>();
    OpenSslSecurityModule security { credentials };
};

namespace
{

// P-256 private key generated by OpenSSL
const ByteBuffer p256_scalar {
    0xCC, 0x17, 0x13, 0x89, 0x94, 0x14, 0x3B, 0xF2, 0x09, 0xF0, 0x7B, 0x49, 0xDA, 0x7E, 0x4E, 0x34,
    0x28, 0x93, 0x99, 0x70, 0x68, 0xDD, 0x84, 0x61, 0x22, 0xE0, 0x6F, 0x93, 0x57, 0x06, 0xA6, 0x2D
};

// BrainpoolP384r1 private key generated by OpenSSL, its public key has an odd y coordinate
const ByteBuffer bp384_scalar {
    0x67, 0x65, 0x0E, 0x03, 0x79, 0xB2, 0x68, 0x56, 0x6C, 0xC7, 0x34, 0xFA, 0xA3, 0x04, 0xEF, 0x19,
    0x92, 0x3C, 0x93, 0x63, 0xDC, 0x22, 0xC6, 0xC0, 0x50, 0x3B, 0x13, 0x35, 0xA8, 0xEB, 0x6C, 0xB5,
    0x94, 0xD7, 0x9C, 0xB4, 0xAA, 0xFF, 0x2B, 0x7A, 0x37, 0xF4, 0x5C, 0x74, 0xA9, 0xED, 0x28, 0x2E
};

KeyReference make_reference(KeyType type, ByteBuffer scalar)
{
    scalar.insert(scalar.begin(), static_cast<std::uint8_t>(type));
    return KeyReference { std::move(scalar) };
}

const struct
{
    const char* defect;
    KeyReference key;
} malformed_references[] = {
    { "empty", KeyReference {} },
    { "unknown key type", KeyReference { ByteBuffer { 0xDE, 0xAD, 0xBE, 0xEF } } },
    { "unspecified key type", make_reference(KeyType::Unspecified, ByteBuffer {}) },
    { "scalar too short for key type", make_reference(KeyType::BrainpoolP384r1, p256_scalar) },
    { "scalar too long for key type", make_reference(KeyType::NistP256, ByteBuffer(33, 0x11)) },
    { "zero scalar", make_reference(KeyType::NistP256, ByteBuffer(32, 0x00)) },
    { "scalar exceeds group order", make_reference(KeyType::NistP256, ByteBuffer(32, 0xFF)) },
};

} // namespace

TEST_F(OpenSslSecurityModuleTest, key_reference_is_key_type_followed_by_scalar)
{
    expected<PublicKey> public_key = security.public_key(make_reference(KeyType::NistP256, p256_scalar));
    ASSERT_TRUE(public_key.has_value());
    EXPECT_EQ("0287B2921E751D320F90CAD8BB67161EFD26659A4B3D66BA7CCC2FF4843283C704",
        vanetza::security::canonical_hexstring(*public_key));

    public_key = security.public_key(make_reference(KeyType::BrainpoolP384r1, bp384_scalar));
    ASSERT_TRUE(public_key.has_value());
    EXPECT_EQ("034EB2F31B770AF48A4892B21B0C11FF68B69C53E1D6C42C02DD66918F1D2718D3E0E7DC636E34BFEF803330B44E383804",
        vanetza::security::canonical_hexstring(*public_key));
}

TEST_F(OpenSslSecurityModuleTest, malformed_key_reference_cannot_sign)
{
    const ByteBuffer digest(32, 0x5A);
    for (const auto& malformed : malformed_references) {
        SCOPED_TRACE(malformed.defect);
        expected<Signature> signature = security.sign(digest, malformed.key);
        ASSERT_TRUE(signature.has_error());
        EXPECT_EQ(SecurityModuleError::InvalidKeyReference, signature.error());
    }
}

TEST_F(OpenSslSecurityModuleTest, malformed_key_reference_has_no_public_key)
{
    for (const auto& malformed : malformed_references) {
        SCOPED_TRACE(malformed.defect);
        expected<PublicKey> public_key = security.public_key(malformed.key);
        ASSERT_TRUE(public_key.has_error());
        EXPECT_EQ(SecurityModuleError::InvalidKeyReference, public_key.error());
    }
}

TEST_F(OpenSslSecurityModuleTest, created_signing_key_is_stored)
{
    expected<KeyReference> key = security.create_signing_key(KeyType::NistP256);
    ASSERT_TRUE(key.has_value());
    expected<PublicKey> public_key = security.public_key(*key);
    ASSERT_TRUE(public_key.has_value());
    boost::optional<PrivateKey> stored = credentials->fetch(*public_key);
    ASSERT_TRUE(stored);
    EXPECT_EQ(KeyType::NistP256, stored->type);
    EXPECT_EQ(ByteBuffer(key->data.begin() + 1, key->data.end()), stored->key);
}

TEST_F(OpenSslSecurityModuleTest, discarded_key_is_removed_from_storage)
{
    expected<KeyReference> key = security.create_signing_key(KeyType::NistP256);
    ASSERT_TRUE(key.has_value());
    expected<PublicKey> public_key = security.public_key(*key);
    ASSERT_TRUE(public_key.has_value());
    ASSERT_TRUE(credentials->fetch(*public_key));
    EXPECT_TRUE(security.discard_key(*key));
    EXPECT_FALSE(credentials->fetch(*public_key));
}

TEST_F(OpenSslSecurityModuleTest, malformed_key_reference_cannot_be_discarded)
{
    for (const auto& malformed : malformed_references) {
        SCOPED_TRACE(malformed.defect);
        EXPECT_FALSE(security.discard_key(malformed.key));
    }
}

TEST_F(OpenSslSecurityModuleTest, stored_key_is_found_by_its_public_key)
{
    const KeyReference reference = make_reference(KeyType::NistP256, p256_scalar);
    expected<PublicKey> public_key = security.public_key(reference);
    ASSERT_TRUE(public_key.has_value());
    PrivateKey stored;
    stored.type = KeyType::NistP256;
    stored.key = p256_scalar;
    credentials->store(*public_key, stored);

    expected<KeyReference> found = security.find_signing_key(*public_key);
    ASSERT_TRUE(found.has_value());
    EXPECT_EQ(reference.data, found->data);
}

TEST_F(OpenSslSecurityModuleTest, unknown_key_is_not_found)
{
    expected<PublicKey> public_key = security.public_key(make_reference(KeyType::NistP256, p256_scalar));
    ASSERT_TRUE(public_key.has_value());
    expected<KeyReference> found = security.find_signing_key(*public_key);
    ASSERT_TRUE(found.has_error());
    EXPECT_EQ(SecurityModuleError::KeyNotFound, found.error());
}

TEST_F(OpenSslSecurityModuleTest, corrupt_stored_key_is_not_usable_for_signing)
{
    expected<PublicKey> public_key = security.public_key(make_reference(KeyType::NistP256, p256_scalar));
    ASSERT_TRUE(public_key.has_value());
    PrivateKey corrupt;
    corrupt.type = KeyType::NistP256;
    corrupt.key = ByteBuffer(32, 0x00);
    credentials->store(*public_key, corrupt);

    expected<KeyReference> found = security.find_signing_key(*public_key);
    ASSERT_TRUE(found.has_error());
    EXPECT_EQ(SecurityModuleError::ModuleFailure, found.error());
}

TEST_F(OpenSslSecurityModuleTest, invalid_recipient_key_is_reported_with_openssl_error)
{
    PublicKey recipient;
    recipient.type = KeyType::NistP256;
    recipient.compression = KeyCompression::NoCompression;
    recipient.x.assign(32, 0x11); // not on curve
    recipient.y.assign(32, 0x11);
    expected<EncryptedSymmetricKey> encrypted = security.encrypt_key(recipient, Aes128Key {}, Sha256Hash {});
    ASSERT_TRUE(encrypted.has_error());
    EXPECT_EQ(SecurityModuleError::InvalidPublicKey, encrypted.error());
    EXPECT_STREQ("openssl.invalid_public_key", encrypted.error().category().name());
    EXPECT_EQ(0u, ERR_peek_error());
}

TEST_F(OpenSslSecurityModuleTest, tampered_ciphertext_is_reported_with_openssl_error)
{
    const Aes128Key key {};
    expected<AesCcmCiphertext> ciphertext = security.encrypt_aes_ccm(key, ByteBuffer(10, 0x5A));
    ASSERT_TRUE(ciphertext.has_value());
    ciphertext->ciphertext.back() ^= 0x01; // authentication tag
    expected<ByteBuffer> decrypted = security.decrypt_aes_ccm(key, *ciphertext);
    ASSERT_TRUE(decrypted.has_error());
    EXPECT_EQ(SecurityModuleError::DecryptionFailure, decrypted.error());
    EXPECT_STREQ("openssl.decryption_failure", decrypted.error().category().name());
    EXPECT_EQ(0u, ERR_peek_error());
}

TEST_F(OpenSslSecurityModuleTest, out_of_range_signature_leaves_openssl_error_queue_unchanged)
{
    expected<PublicKey> public_key = security.public_key(make_reference(KeyType::NistP256, p256_scalar));
    ASSERT_TRUE(public_key.has_value());
    Signature signature;
    signature.type = KeyType::NistP256;
    signature.r = ByteBuffer { 0x00 }; // valid r and s are greater than zero
    signature.s = ByteBuffer { 0x00 };

    // error queued by someone else before verification
    ERR_raise(ERR_LIB_EC, EC_R_POINT_IS_NOT_ON_CURVE);
    const unsigned long queued = ERR_peek_last_error();

    EXPECT_FALSE(security.verify(Sha256Hash {}, signature, *public_key));
    EXPECT_EQ(queued, ERR_get_error());
    EXPECT_EQ(0u, ERR_peek_error());
}
